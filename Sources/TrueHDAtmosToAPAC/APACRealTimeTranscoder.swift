import Foundation
import AVFAudio
import AudioToolbox
import CoreAudioTypes
import CoreMedia

/// Errors that can occur during real-time APAC transcoding.
public enum APACTranscoderError: Error, CustomStringConvertible {
    case unsupportedChannelLayout(AudioChannelLayoutTag)
    case converterCreationFailed
    case formatDescriptionCreationFailed(OSStatus)
    case sampleBufferCreationFailed(OSStatus)
    case encodingFailed(NSError?)

    public var description: String {
        switch self {
        case .unsupportedChannelLayout(let tag):
            return "Unsupported AudioChannelLayoutTag for APAC: \(tag)"
        case .converterCreationFailed:
            return "Failed to initialize AVAudioConverter for kAudioFormatAPAC"
        case .formatDescriptionCreationFailed(let status):
            return "CMAudioFormatDescriptionCreate failed with OSStatus \(status)"
        case .sampleBufferCreationFailed(let status):
            return "CMAudioSampleBufferCreateWithPacketDescriptions failed with OSStatus \(status)"
        case .encodingFailed(let err):
            return "APAC encoding failed: \(String(describing: err))"
        }
    }
}

/// Real-time transcoder that takes 3D-rendered PCM (`Atmos 7.1.4` or `Atmos 9.1.6`),
/// encodes it on the fly into `kAudioFormatAPAC` (`'apac'`), and packages compressed packets
/// into `CMSampleBuffer` instances ready for `AVSampleBufferAudioRenderer` on tvOS.
public final class APACRealTimeTranscoder {
    public static let framesPerAPACPacket: Int = 1024

    public let targetLayout: AtmosTargetLayout
    public let sampleRate: Double
    public let bitRate: Int
    public let pcmInputFormat: AVAudioFormat
    public let apacOutputFormat: AVAudioFormat

    private let converter: AVAudioConverter
    private let channelLayout: AVAudioChannelLayout
    private(set) public var cmFormatDescription: CMAudioFormatDescription

    /// Deinterleaved PCM FIFO queue accumulating arbitrary input block sizes (e.g. 40-sample TrueHD AUs)
    /// into 1024-frame APAC packets.
    private var fifoChannels: [[Float]]
    private var fifoFrameCount: Int = 0

    /// Presentation timestamp counter in sample frames at `sampleRate`.
    private(set) public var encodedSampleFrames: Int64 = 0
    private(set) public var encodedPacketCount: Int64 = 0

    /// Reusable buffer kept alive across `AVAudioConverterInputBlock` invocations as required by Apple docs.
    private var activeInputPCMBuffer: AVAudioPCMBuffer?

    public init(
        targetLayout: AtmosTargetLayout = .atmos7_1_4,
        sampleRate: Double = 48000.0,
        bitRate: Int = 1_280_000,
        disableDRC: Bool = true
    ) throws {
        self.targetLayout = targetLayout
        self.sampleRate = sampleRate
        self.bitRate = bitRate

        guard let layout = AVAudioChannelLayout(layoutTag: targetLayout.channelLayoutTag) else {
            throw APACTranscoderError.unsupportedChannelLayout(targetLayout.channelLayoutTag)
        }
        self.channelLayout = layout

        let inFormat = AVAudioFormat(standardFormatWithSampleRate: sampleRate, channelLayout: layout)
        self.pcmInputFormat = inFormat

        var outDesc = AudioStreamBasicDescription(
            mSampleRate: sampleRate,
            mFormatID: kAudioFormatAPAC,
            mFormatFlags: 0,
            mBytesPerPacket: 0,
            mFramesPerPacket: UInt32(Self.framesPerAPACPacket),
            mBytesPerFrame: 0,
            mChannelsPerFrame: UInt32(targetLayout.channelCount),
            mBitsPerChannel: 0,
            mReserved: 0
        )

        guard let outFormat = AVAudioFormat(streamDescription: &outDesc, channelLayout: layout),
              let conv = AVAudioConverter(from: inFormat, to: outFormat) else {
            throw APACTranscoderError.converterCreationFailed
        }

        conv.bitRate = bitRate
        conv.contentSource = .passthrough
        conv.dynamicRangeControlConfiguration = disableDRC ? .none : .movie
        conv.audioSyncPacketFrequency = 75

        self.apacOutputFormat = conv.outputFormat
        self.converter = conv
        self.fifoChannels = Array(repeating: [Float](), count: targetLayout.channelCount)

        // Create CMAudioFormatDescription with the 'dapa' magic cookie generated by the APAC encoder
        let cookieData = conv.magicCookie ?? Data()
        var formatDesc: CMAudioFormatDescription?
        let status = cookieData.withUnsafeBytes { cookiePtr in
            CMAudioFormatDescriptionCreate(
                allocator: kCFAllocatorDefault,
                asbd: conv.outputFormat.streamDescription,
                layoutSize: MemoryLayout<AudioChannelLayout>.size,
                layout: layout.layout,
                magicCookieSize: cookieData.count,
                magicCookie: cookiePtr.baseAddress,
                extensions: nil,
                formatDescriptionOut: &formatDesc
            )
        }
        guard status == noErr, let validFormatDesc = formatDesc else {
            throw APACTranscoderError.formatDescriptionCreationFailed(status)
        }
        self.cmFormatDescription = validFormatDesc
    }

    /// Appends a rendered multichannel PCM buffer (`Atmos 7.1.4` or `Atmos 9.1.6`) into the FIFO
    /// and returns any ready `CMSampleBuffer` packets encoded in `kAudioFormatAPAC`.
    public func pushPCMAndEncode(_ pcmBuffer: AVAudioPCMBuffer) throws -> [CMSampleBuffer] {
        let frames = Int(pcmBuffer.frameLength)
        guard frames > 0, let chData = pcmBuffer.floatChannelData else { return [] }

        let numChannels = targetLayout.channelCount
        for c in 0..<numChannels {
            let ptr = UnsafeBufferPointer(start: chData[c], count: frames)
            fifoChannels[c].append(contentsOf: ptr)
        }
        fifoFrameCount += frames

        var outputSampleBuffers = [CMSampleBuffer]()

        // Encode in chunks of 1024 frames (1 APAC packet)
        while fifoFrameCount >= Self.framesPerAPACPacket {
            if let sb = try encodeSingleAPACPacket(frameCount: Self.framesPerAPACPacket) {
                outputSampleBuffers.append(sb)
            }
        }

        return outputSampleBuffers
    }

    /// Flushes any remaining PCM frames at end-of-stream by zero-padding to a 1024-frame boundary.
    public func flush() throws -> [CMSampleBuffer] {
        guard fifoFrameCount > 0 else { return [] }
        let pad = Self.framesPerAPACPacket - fifoFrameCount
        if pad > 0 {
            for c in 0..<targetLayout.channelCount {
                fifoChannels[c].append(contentsOf: repeatElement(0.0, count: pad))
            }
            fifoFrameCount += pad
        }
        if let sb = try encodeSingleAPACPacket(frameCount: Self.framesPerAPACPacket) {
            return [sb]
        }
        return []
    }

    private func encodeSingleAPACPacket(frameCount: Int) throws -> CMSampleBuffer? {
        let numChannels = targetLayout.channelCount
        guard let inputBuf = AVAudioPCMBuffer(pcmFormat: pcmInputFormat, frameCapacity: AVAudioFrameCount(frameCount)) else {
            return nil
        }
        inputBuf.frameLength = AVAudioFrameCount(frameCount)

        if let dstChannels = inputBuf.floatChannelData {
            for c in 0..<numChannels {
                fifoChannels[c].withUnsafeBufferPointer { srcPtr in
                    _ = memcpy(dstChannels[c], srcPtr.baseAddress!, frameCount * MemoryLayout<Float>.size)
                }
                fifoChannels[c].removeFirst(frameCount)
            }
        }
        fifoFrameCount -= frameCount

        // Keep reference alive during conversion as mandated by AVAudioConverterInputBlock documentation
        self.activeInputPCMBuffer = inputBuf

        let compBuf = AVAudioCompressedBuffer(
            format: apacOutputFormat,
            packetCapacity: 1,
            maximumPacketSize: converter.maximumOutputPacketSize
        )

        var nsError: NSError?
        var supplied = false
        let status = converter.convert(to: compBuf, error: &nsError) { [weak self] _, outStatus in
            guard let self = self, !supplied, let buf = self.activeInputPCMBuffer else {
                outStatus.pointee = .noDataNow
                return nil
            }
            supplied = true
            outStatus.pointee = .haveData
            return buf
        }

        if status == .error {
            throw APACTranscoderError.encodingFailed(nsError)
        }

        guard compBuf.packetCount > 0, compBuf.byteLength > 0 else {
            return nil
        }

        let sampleBuffer = try createCMSampleBuffer(from: compBuf)
        encodedSampleFrames += Int64(frameCount)
        encodedPacketCount += Int64(compBuf.packetCount)
        return sampleBuffer
    }

    private func createCMSampleBuffer(from compBuf: AVAudioCompressedBuffer) throws -> CMSampleBuffer {
        let byteLen = Int(compBuf.byteLength)
        var blockBuffer: CMBlockBuffer?

        var status = CMBlockBufferCreateWithMemoryBlock(
            allocator: kCFAllocatorDefault,
            memoryBlock: nil,
            blockLength: byteLen,
            blockAllocator: kCFAllocatorDefault,
            customBlockSource: nil,
            offsetToData: 0,
            dataLength: byteLen,
            flags: 0,
            blockBufferOut: &blockBuffer
        )
        guard status == kCMBlockBufferNoErr, let validBlockBuffer = blockBuffer else {
            throw APACTranscoderError.sampleBufferCreationFailed(status)
        }

        status = CMBlockBufferReplaceDataBytes(
            with: compBuf.data,
            blockBuffer: validBlockBuffer,
            offsetIntoDestination: 0,
            dataLength: byteLen
        )
        guard status == kCMBlockBufferNoErr else {
            throw APACTranscoderError.sampleBufferCreationFailed(status)
        }

        let pts = CMTime(value: encodedSampleFrames, timescale: CMTimeScale(sampleRate))
        var sampleBuffer: CMSampleBuffer?

        status = CMAudioSampleBufferCreateWithPacketDescriptions(
            allocator: kCFAllocatorDefault,
            dataBuffer: validBlockBuffer,
            dataReady: true,
            makeDataReadyCallback: nil,
            refcon: nil,
            formatDescription: cmFormatDescription,
            sampleCount: CMItemCount(compBuf.packetCount),
            presentationTimeStamp: pts,
            packetDescriptions: compBuf.packetDescriptions,
            sampleBufferOut: &sampleBuffer
        )
        guard status == noErr, let validSampleBuffer = sampleBuffer else {
            throw APACTranscoderError.sampleBufferCreationFailed(status)
        }

        return validSampleBuffer
    }
}
